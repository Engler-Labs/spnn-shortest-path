def light_cycles(n, adj, edges, w, limit_weight, max_cycles=400):
    """Bounded enumeration of light cycles (for each edge, the lightest cycle through it),
    no heavier than `limit_weight`.  Heuristic -- exhibits witnesses, never claims absence."""
    out = []
    order = sorted(range(len(edges)), key=lambda i: float(w[i]))
    for i in order:
        if len(out) >= max_cycles:
            break
        we = float(w[i])
        if we >= limit_weight:
            break
        u, v = int(edges[i][0]), int(edges[i][1])
        limit = limit_weight - we
        dist = {u: 0.0}
        prev = {u: None}
        pq = [(0.0, u)]
        found = None
        while pq:
            d, x = heapq.heappop(pq)
            if d > dist.get(x, float("inf")):
                continue
            if x == v:
                found = d
                break
            if d >= limit:
                break
            for y, wy in adj[x]:
                if x == u and y == v and abs(wy - we) < TOL:
                    continue
                nd = d + wy
                if nd >= limit:
                    break
                if nd < dist.get(y, float("inf")):
                    dist[y] = nd
                    prev[y] = x
                    heapq.heappush(pq, (nd, y))
        if found is None:
            continue
        cyc = [v]
        x = prev.get(v)
        while x is not None:
            cyc.append(x)
            x = prev.get(x)
        out.append((found + we, cyc))
    out.sort(key=lambda c: c[0])
    return out


def edge_sum_bounds(ls, m):
    """The two rigorous light-edge lower bounds on delta + W*.  Returns
    (sharp_all, sharp_pathge2, form39) where form39 = Lsum(m) - w_max is (39)'s own shape."""
    e = [ls[i] - ls[i - 1] for i in range(1, len(ls))]
    pathge2 = ls[m - 2] + (e[m - 2] + e[m - 1]) / 2.0
    one_edge = ls[m - 1]
    return min(pathge2, one_edge), pathge2, one_edge


def cycle_leg(n, adj, edges, w, L, wstar, girth, ls, wmax):
    """Close the cycle-carrying leg, or report it OPEN.  Returns (kind, bound, note)."""
    m = L + 2
    sharp_all, _p2, _one = edge_sum_bounds(ls, m)
    if sharp_all > wstar + TOL:
        return "LIGHT_EDGE_SUM", sharp_all - wstar, "closes BOTH legs at once"
    if girth > wstar + TOL:
        return "GIRTH", girth - wstar, "bracket >= 0 and every cycle weighs >= girth"
    return ("OPEN", max(girth, sharp_all) - wstar,
            "neither certificate fires -- constructive search, then UNDETERMINED")


def cycle_witness_hunt(n, adj, edges, w, L, wstar, g, budget_cycles=250, max_packings=60):
    """BOUNDED constructive search for a cycle-carrying member with delta <= 0.  One-directional:
    a hit is a rigorous witness; a miss proves nothing (UNDETERMINED)."""
    m = L + 2
    cyc = light_cycles(n, adj, edges, w, wstar + TOL, max_cycles=budget_cycles)
    if not cyc:
        return None
    best = None
    tried = 0
    for i0 in range(min(len(cyc), max_packings)):
        used = bytearray(n)
        chosen = []
        q = 0
        wc = 0.0
        order = [cyc[i0]] + [c for j, c in enumerate(cyc) if j != i0]
        for cw, verts in order:
            if any(used[v] for v in verts):
                continue
            if q + len(verts) > m - 1:
                continue
            for v in verts:
                used[v] = 1
            chosen.append((cw, verts))
            q += len(verts)
            wc += cw
            if wc - wstar > 0:
                break
            p = m - q
            if p < 1:
                break
            tried += 1
            if tried > max_packings * 4:
                return best
            if p == 1:
                lightest = None
                for (a, b), ww in zip(edges, w):
                    a, b = int(a), int(b)
                    if used[a] or used[b]:
                        continue
                    if lightest is None or float(ww) < lightest[0]:
                        lightest = (float(ww), [a, b])
                if lightest is None:
                    continue
                bracket, pwalk, pws = 0.0, lightest[1], [lightest[0]]
            else:
                res = _search_free_start(adj, p, 0.0, g, float("inf"), "cycle_path",
                                         {"nodes": 0}, forbidden=used, raise_on_hit=False)
                bracket, hold = res
                if hold["walk"] is None:
                    continue
                pwalk, pws = hold["walk"], hold["ws"]
            d = bracket + wc - wstar
            if best is None or d < best["delta"]:
                best = dict(delta=d, cycles=[(c, list(v)) for c, v in chosen],
                            path_walk=pwalk, path_weights=pws, q=q, p=p, w_cyc=wc,
                            bracket=bracket)
            if d <= TOL:
                return best
    return best


