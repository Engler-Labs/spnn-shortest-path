def _summarise(rows):
    split = {}
    for fam in FAMILIES + ["POOLED"]:
        sel = rows if fam == "POOLED" else [r for r in rows if r["family"] == fam]
        c = {"WITNESS": 0, "TIE": 0, "CERTIFIED": 0, "UNDETERMINED": 0}
        for r in sel:
            c[r["verdict"]] = c.get(r["verdict"], 0) + 1
        split[fam] = dict(n=len(sel), **c)

    subcases = {}
    for r in rows:
        if r["verdict"] in ("WITNESS", "TIE"):
            subcases[r["witness_subcase"]] = subcases.get(r["witness_subcase"], 0) + 1

    anchored = sum(1 for r in rows if r["verdict"] in ("WITNESS", "TIE")
                   and r["witness_subcase"] in ("one_aux_S", "one_aux_T"))

    # median witness gap in energy at c=4, pooled + terrain
    def gaps(sel):
        out = []
        for r in sel:
            d = (_f(r["delta_min_pure"]) if r["witness_subcase"] != "cycle_carrying"
                 else _f(r.get("cycle_witness_delta", "nan")))
            wm = _f(r["wmax"])
            if not math.isnan(d) and wm > 0:
                out.append(2.0 * 4.0 * d / (2.0 * wm))
        return out
    wit = [r for r in rows if r["verdict"] == "WITNESS"]
    gap_pooled = _quantiles(gaps(wit))
    gap_terrain = _quantiles(gaps([r for r in wit if r["family"] == "mtn_knn"]))

    # sparse N=60 cell
    cell4040 = [r for r in rows if r["family"] == "sparse" and int(r["size"]) == 60]
    cell4040_wit = sum(1 for r in cell4040 if r["verdict"] == "WITNESS")

    # rho rider
    n39 = sum(1 for r in rows if _f(r["cert39_margin"]) > TOL)
    nsharp = sum(1 for r in rows if _f(r["cert_sharp_margin"]) > TOL)
    sharp_only = sum(1 for r in rows
                     if _f(r["cert_sharp_margin"]) > TOL >= _f(r["cert39_margin"]))
    form39_only = sum(1 for r in rows
                      if _f(r["cert39_margin"]) > TOL >= _f(r["cert_sharp_margin"]))
    id_errors = sum(1 for r in rows
                    if (_f(r["gamma"]) >= _f(r["gamma_threshold"]))
                    != (_f(r["cert39_margin"]) > TOL))
    below = [r for r in rows if _f(r["rho"]) < 0.25]
    fires_below = sum(1 for r in below if _f(r["cert39_margin"]) > TOL)
    gamma_max = max(_f(r["gamma"]) for r in rows)
    gamma_viol = sum(1 for r in rows if _f(r["gamma"]) > 1.0 + 1e-12)

    return dict(
        n_rows=len(rows), split=split, witness_subcases=subcases,
        anchored_witnesses=anchored,
        witness_gap_at_c4_pooled=gap_pooled, witness_gap_at_c4_terrain=gap_terrain,
        sparse_N60_cell=dict(n=len(cell4040), WITNESS=cell4040_wit),
        rho_rider=dict(form39_fires=n39, sharp_fires=nsharp, sharp_only=sharp_only,
                       form39_only=form39_only, form39_identity_errors=id_errors,
                       form39_fires_below_quarter=fires_below,
                       gamma_max=gamma_max, gamma_violations=gamma_viol),
    )


def run(argv=None) -> dict:
    argv = argv or []
    if "--regenerate" in argv:
        return _regenerate()

    # ---- reference anchor (independent of the committed sweep)
    anc = anchor()
    assert anc["all_agree"], f"reference anchor FAILED: {anc['checks']}"

    rows = _load_verdicts()
    pop = _population()

    # ---- 1. population anchor: L / W* / (s,t) / |E| vs the campaign CSV
    anchor_fail = 0
    for r in rows:
        c = pop.get((r["family"], int(r["size"]), int(r["seed"])))
        if c is None:
            anchor_fail += 1
            continue
        if int(c["L"]) != int(r["L"]) or abs(float(c["wsum"]) - _f(r["wstar"])) > 1e-9 \
           or int(c["s"]) != int(r["s"]) or int(c["t"]) != int(r["t"]) \
           or int(c["E"]) != int(r["E"]):
            anchor_fail += 1

    # ---- 2. re-verify EVERY witness from a freshly regenerated instance
    wit_rows = [r for r in rows if r["verdict"] in ("WITNESS", "TIE")]
    wit_fail = 0
    for r in wit_rows:
        n, edges, w = _build(r["family"], int(r["size"]), int(r["seed"]))
        s, t, opt = _terminals(n, edges, w)
        L = len(opt) - 1
        wstar = sum(_path_weights(edges, w, opt))
        lut = {}
        for (a, b), ww in zip(edges, w):
            lut[(int(a), int(b))] = float(ww)
            lut[(int(b), int(a))] = float(ww)
        _d, fails = _verify_witness(r, lut, s, t, L, wstar)
        if fails:
            wit_fail += 1

    # ---- 3. re-derive certificates on a declared sample of the CERTIFIED
    cert_rows = [r for r in rows if r["verdict"] == "CERTIFIED"]
    cert_fail = 0
    for r in cert_rows[::20]:
        n, edges, w = _build(r["family"], int(r["size"]), int(r["seed"]))
        s, t, opt = _terminals(n, edges, w)
        L = len(opt) - 1
        m = L + 2
        wstar = sum(_path_weights(edges, w, opt))
        adj = adjacency(n, edges, w)
        ls = prefix_light_sums(w, m)
        sharp, _p2, _oe = edge_sum_bounds(ls, m)
        g, _ex = weighted_girth(n, adj, edges, w)
        ok = (sharp > wstar + TOL) or (g > wstar + TOL)
        if not ok:
            cert_fail += 1

    summ = _summarise(rows)
    summ["population_anchor_disagreements"] = anchor_fail
    summ["witness_verification"] = dict(n=len(wit_rows), failures=wit_fail)
    summ["certificate_recheck"] = dict(sampled=len(cert_rows[::20]), failures=cert_fail)
    summ["reference_anchor"] = dict(n_checks=anc["n_checks"], all_agree=anc["all_agree"],
                                    delta_min=anc["per_subcase"].get("one_aux_S"),
                                    argmin=anc["argmin_subcase"])
    out = write_json("dzero/summary.json", summ)
    json_anchor = write_json("dzero/anchor.json", anc)

    sp = summ["split"]["POOLED"]
    rr = summ["rho_rider"]
    print(f"[20] dzero_population -> {rel(out)}")
    print(f"    reference anchor: {anc['n_checks']} checks, all agree = {anc['all_agree']}; "
          f"delta_min(one_aux_S)={anc['per_subcase']['one_aux_S']:.6f} argmin={anc['argmin_subcase']}")
    print(f"    population anchor (L/W*/s,t/|E| vs campaign): {anchor_fail} disagreements")
    print(f"    witnesses re-verified from regenerated instances: {len(wit_rows)}, "
          f"{wit_fail} failures")
    print(f"    certificate recheck: {len(cert_rows[::20])} sampled, {cert_fail} failures")
    print(f"    SPLIT (n={sp['n']}): WITNESS {sp['WITNESS']} / CERTIFIED {sp['CERTIFIED']} "
          f"/ UNDETERMINED {sp['UNDETERMINED']} (TIE {sp['TIE']})")
    for fam in FAMILIES:
        s2 = summ["split"][fam]
        print(f"      {fam:<8} n={s2['n']:<4} W {s2['WITNESS']:<4} C {s2['CERTIFIED']:<4} "
              f"U {s2['UNDETERMINED']}")
    print(f"    one-terminal-anchored witnesses: {summ['anchored_witnesses']}/{sp['WITNESS']}")
    print(f"    sparse N=60 cell: {summ['sparse_N60_cell']['WITNESS']}/"
          f"{summ['sparse_N60_cell']['n']} WITNESS")
    print(f"    median witness gap@c4: pooled {summ['witness_gap_at_c4_pooled'].get('med'):.2f}, "
          f"terrain {summ['witness_gap_at_c4_terrain'].get('med'):.2f}")
    print(f"    rho rider: form39 fires {rr['form39_fires']}, sharp {rr['sharp_fires']} "
          f"(+{rr['sharp_only']} sharp-only), identity errors {rr['form39_identity_errors']}, "
          f"form39 fires below rho=1/4: {rr['form39_fires_below_quarter']}, "
          f"gamma_max {rr['gamma_max']:.5f} ({rr['gamma_violations']} violations)")

    # ---- ASSERT the headline figures the manuscript prints
    assert anchor_fail == 0, f"population anchor: {anchor_fail} disagreements"
    assert wit_fail == 0, f"witness re-verification: {wit_fail} failures"
    assert cert_fail == 0, f"certificate recheck: {cert_fail} failures"
    assert (sp["WITNESS"], sp["CERTIFIED"], sp["UNDETERMINED"]) == (651, 276, 100), sp
    assert summ["split"]["sparse"]["WITNESS"] == 205 and summ["split"]["sparse"]["n"] == 223
    assert summ["split"]["dense"]["WITNESS"] == 170 and summ["split"]["dense"]["n"] == 182
