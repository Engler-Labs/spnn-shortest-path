def measure_instance(family, size, seed):
    """Full three-way verdict for one instance, using the public-repo generators."""
    row = dict(family=family, size=size, seed=seed, label=f"{family}_N{size}_seed{seed}")
    t_all = time.time()

    n, edges, w = _build(family, size, seed)
    s, t, opt_path = _terminals(n, edges, w)
    if opt_path is None:
        row.update(status="no_path", verdict="UNDETERMINED",
                   censor_note="terminals not connected")
        return row
    L = len(opt_path) - 1
    m = L + 2
    wstar = sum(_path_weights(edges, w, opt_path))
    wmax = max(float(x) for x in w)
    adj = adjacency(n, edges, w)
    ls = prefix_light_sums(w, m)
    lightsum_m = ls[m]
    sharp_all, sharp_pathge2, one_edge_branch = edge_sum_bounds(ls, m)
    rho = (wstar / L) / (2.0 * wmax) if L else float("nan")

    row.update(status="ok", N=n, E=len(edges), s=s, t=t, terminal_fallback=0,
               L=L, m=m, wstar=wstar, wmax=wmax, lightsum_m=lightsum_m,
               lightsum_m_minus_1=ls[m - 1],
               cert_sharp_margin=sharp_all - wstar,
               cert_pure_margin=sharp_pathge2 - wstar,
               cert39_margin=lightsum_m - wmax - wstar,
               rho=rho,
               gamma=(lightsum_m / m) / (wstar / L) if L else float("nan"),
               gamma_threshold=((L + 1.0 / (2.0 * rho)) / m) if L else float("nan"),
               gamma_sharp=(ls[m - 1] / (m - 1)) / (wstar / L) if L else float("nan"),
               gamma_sharp_threshold=L / (m - 1.0) if L else float("nan"))

    # cycle leg (girth + light-edge certificate)
    t0 = time.time()
    girth, girth_exact = weighted_girth(n, adj, edges, w)
    row["girth"] = girth
    row["girth_exact"] = int(girth_exact)
    kind, bound, note = cycle_leg(n, adj, edges, w, L, wstar, girth, ls, wmax)
    row["cycle_cert"] = kind
    row["cycle_bound"] = bound
    row["cycle_note"] = note
    row["cycle_wall_s"] = time.time() - t0

    # pure-path leg
    t0 = time.time()
    row["pure_status"] = "ok"
    try:
        dmin, per, nodes = pure_path_leg(n, adj, s, t, L, wstar, opt_path)
        row["delta_min_pure"] = dmin
        for k, v in per.items():
            row[f"delta_{k}"] = v
        row["dfs_nodes"] = nodes
        row["argmin_subcase"] = min(per, key=lambda k: per[k]) if per else ""
    except Witness as wit:
        row["pure_status"] = "witness"
        row["delta_min_pure"] = wit.delta
        row["witness_subcase"] = wit.sub
        row["witness_walk"] = " ".join(str(x) for x in wit.walk)
        row["witness_weights"] = " ".join("%.9g" % x for x in wit.weights)
    row["pure_wall_s"] = time.time() - t0

    row["verdict"], row["verdict_note"] = _verdict(row, n, adj, edges, w, L, wstar,
                                                   walk_lb_free_end(n, adj, m))
    row["total_wall_s"] = time.time() - t_all
    return row


def _verdict(row, n, adj, edges, w, L, wstar, g):
    if row.get("pure_status") == "witness":
        d = row["delta_min_pure"]
        return ("WITNESS" if d < -TOL else "TIE"), f"pure-path {row.get('witness_subcase')}"
    if row.get("pure_status") != "ok":
        return "UNDETERMINED", f"pure leg {row.get('pure_status')}"
    if row.get("cycle_cert") in ("GIRTH", "LIGHT_EDGE_SUM"):
        return "CERTIFIED", row["cycle_cert"]
    hit = cycle_witness_hunt(n, adj, edges, w, L, wstar, g)
    if hit is not None:
        row["cycle_witness_delta"] = hit["delta"]
        if hit["delta"] <= TOL:
            row["witness_subcase"] = "cycle_carrying"
            row["witness_walk"] = json.dumps(hit["cycles"])
            row["witness_weights"] = " ".join("%.9g" % x for x in hit["path_weights"])
            return ("WITNESS" if hit["delta"] < -TOL else "TIE"), "cycle-carrying member"
    return "UNDETERMINED", "cycle leg OPEN (neither certificate fired, no witness found)"


