def adjacency(n, edges, w):
    """Adjacency lists of (nbr, weight), sorted ASCENDING by weight so a DFS meets the
    light configurations first."""
    a = [[] for _ in range(n)]
    for (u, v), ww in zip(edges, w):
        u, v, ww = int(u), int(v), float(ww)
        a[u].append((v, ww))
        a[v].append((u, ww))
    for lst in a:
        lst.sort(key=lambda t: t[1])
    return a


def _path_weights(edges, w, path):
    lut = {}
    for (a, b), ww in zip(edges, w):
        a, b, ww = int(a), int(b), float(ww)
        lut[(a, b)] = ww
        lut[(b, a)] = ww
    return [lut[(path[i], path[i + 1])] for i in range(len(path) - 1)]


def prefix_light_sums(w, upto):
    """out[k] = sum of the k lightest edge weights (inf padding if fewer than `upto`)."""
    ws = sorted(float(x) for x in w)
    out = [0.0]
    for i in range(min(upto, len(ws))):
        out.append(out[-1] + ws[i])
    while len(out) <= upto:
        out.append(float("inf"))
    return out


def weighted_girth(n, adj, edges, w, cap=None):
    """Exact minimum-weight cycle: for each edge (u,v), the lightest u->v path in G minus
    that edge closes a cycle; the minimum over edges is the weighted girth."""
    order = sorted(range(len(edges)), key=lambda i: float(w[i]))
    best = float("inf")
    exact = True
    for i in order:
        we = float(w[i])
        u, v = int(edges[i][0]), int(edges[i][1])
        if we >= best:
            break
        if cap is not None and best < cap:
            exact = False
            break
        limit = best - we
        dist = {u: 0.0}
        pq = [(0.0, u)]
        duv = float("inf")
        while pq:
            d, x = heapq.heappop(pq)
            if d > dist.get(x, float("inf")):
                continue
            if x == v:
                duv = d
                break
            if d >= limit:
                break
            for y, wy in adj[x]:
                if x == u and y == v and abs(wy - we) < TOL:
                    continue
                nd = d + wy
                if nd >= limit:
                    break
                if nd < dist.get(y, float("inf")):
                    dist[y] = nd
                    heapq.heappush(pq, (nd, y))
        if duv + we < best:
            best = duv + we
    return best, exact


# ---------------------------------------------------------------------------
# ADMISSIBLE BOUNDS -- exact r-edge WALK relaxations (walks superset simple paths,
# so a min over walks lower-bounds the min over paths).  Each O(m * |E|).
# ---------------------------------------------------------------------------
def walk_lb_free_end(n, adj, rmax):
    """g[k][v] = min over k-edge walks from v of (weight - last edge / 2), k >= 1."""
    INF = float("inf")
    g = [[INF] * n for _ in range(rmax + 1)]
    if rmax >= 1:
        for v in range(n):
            g[1][v] = (adj[v][0][1] / 2.0) if adj[v] else INF
    for k in range(2, rmax + 1):
        gk, gp = g[k], g[k - 1]
        for v in range(n):
            best = INF
            for u, wu in adj[v]:
                if wu >= best:
                    break
                c = wu + gp[u]
                if c < best:
                    best = c
            gk[v] = best
    return g


def walk_lb_to_target(n, adj, target, rmax):
    """h[k][v] = min weight of a k-edge walk from v to `target`."""
    INF = float("inf")
    h = [[INF] * n for _ in range(rmax + 1)]
    h[0][target] = 0.0
    for k in range(1, rmax + 1):
        hk, hp = h[k], h[k - 1]
        for v in range(n):
            best = INF
            for u, wu in adj[v]:
                if wu >= best:
                    break
                c = wu + hp[u]
                if c < best:
                    best = c
            hk[v] = best
    return h


