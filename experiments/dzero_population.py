# WITNESS RE-VERIFICATION (the CI-relevant proof)
# ---------------------------------------------------------------------------
def _verify_witness(row, lut, s, t, L, wstar):
    m = L + 2
    sub = row["witness_subcase"]
    fails = []
    if sub == "cycle_carrying":
        cycles = json.loads(row["witness_walk"])
        pws = [float(x) for x in row["witness_weights"].split()] if row["witness_weights"] else []
        seen = set()
        q = 0
        wcyc = 0.0
        for cw, verts in cycles:
            if len(set(verts)) != len(verts) or (seen & set(verts)):
                fails.append("cycles overlap or repeat a vertex")
            seen |= set(verts)
            tot = 0.0
            for i in range(len(verts)):
                a, b = verts[i], verts[(i + 1) % len(verts)]
                if (a, b) not in lut:
                    fails.append(f"cycle edge {(a, b)} not in G")
                    tot = float("nan")
                    break
                tot += lut[(a, b)]
            if not math.isnan(tot) and abs(tot - cw) > 1e-6:
                fails.append("cycle weight disagrees")
            q += len(verts)
            wcyc += cw
        p = len(pws)
        if q + p != m:
            fails.append(f"edge count {q}+{p} != m={m}")
        bracket = sum(pws) - (pws[0] + pws[-1]) / 2.0 if p > 1 else 0.0
        delta = bracket + wcyc - wstar
        if delta > TOL:
            fails.append(f"delta {delta} positive -- not a witness")
        return delta, fails

    walk = [int(x) for x in row["witness_walk"].split()]
    ws = [float(x) for x in row["witness_weights"].split()]
    if len(set(walk)) != len(walk):
        fails.append("walk repeats a vertex")
    tot = 0.0
    for i in range(len(walk) - 1):
        e = (walk[i], walk[i + 1])
        if e not in lut:
            fails.append(f"edge {e} not in G")
            continue
        if abs(lut[e] - ws[i]) > 1e-6:
            fails.append(f"edge {e} weight mismatch")
        tot += lut[e]
    need = {"both_aux": L, "one_aux_S": L + 1, "one_aux_T": L + 1, "aux_free": L + 2}[sub]
    if len(ws) != need:
        fails.append(f"{sub} needs {need} real edges, has {len(ws)}")
    if sub == "one_aux_S" and walk[0] != s:
        fails.append("one_aux_S must start at s")
    if sub == "one_aux_T" and walk[0] != t:
        fails.append("one_aux_T must start at t")
    if sub == "both_aux" and not (walk[0] == s and walk[-1] == t):
        fails.append("both_aux must run s -> t")
    disc = {"both_aux": 0.0, "one_aux_S": ws[-1] / 2.0, "one_aux_T": ws[-1] / 2.0,
            "aux_free": (ws[0] + ws[-1]) / 2.0}[sub]
    delta = tot - wstar - disc
    if abs(delta - _f(row["delta_min_pure"])) > 1e-6:
        fails.append("delta disagrees with committed value")
    if delta > TOL:
        fails.append(f"delta {delta} positive -- not a witness")
    return delta, fails


