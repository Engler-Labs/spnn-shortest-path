    for i, got in enumerate(ws):
        chk(f"witness edge ({walk[i]},{walk[i+1]})", got, DEPOSIT["weights"][i], tol=5e-5)
    chk("W_real", sum(ws), DEPOSIT["w_real"], tol=5e-6)
    chk("w_end", ws[-1], DEPOSIT["w_end"], tol=5e-6)
    chk("delta(witness)", sum(ws) - wstar - ws[-1] / 2.0, DEPOSIT["delta_min"], tol=5e-7)
    girth, gexact = weighted_girth(n, adj, edges, w)
    chk("weighted girth", girth, DEPOSIT["girth"], tol=5e-6)
    dmin, per, nodes = pure_path_leg(n, adj, s, t, L, wstar, opt_path)
    chk("delta_min (exhaustive)", dmin, DEPOSIT["delta_min"], tol=5e-7)
    for k, v in DEPOSIT["subcase_minima"].items():
        if k in per:
            chk(f"delta_min[{k}]", per[k], v, tol=5e-6)
    argmin = min(per, key=lambda k: per[k]) if per else None
    chk("argmin is one_aux_S", 1 if argmin == "one_aux_S" else 0, 1, "int")
    out["per_subcase"] = per
    out["argmin_subcase"] = argmin
    out["all_agree"] = all(c["agree"] for c in out["checks"])
    out["n_checks"] = len(out["checks"])
    return out


