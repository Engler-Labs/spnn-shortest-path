def _regenerate() -> dict:
    """Re-run the full population sweep natively (tier-2) and rewrite verdicts.csv."""
    anc = anchor()
    if not anc["all_agree"]:
        raise SystemExit(f"reference anchor FAILED -- refusing to sweep: {anc['checks']}")
    write_json("dzero/anchor.json", anc)
    pop_rows = [r for r in csv.DictReader(open(results_path("creq/population.csv"),
                                               encoding="utf-8")) if r["status"] == "ok"]
    rows = []
    t0 = time.time()
    for i, pr in enumerate(pop_rows):
        row = measure_instance(pr["family"], int(pr["size"]), int(pr["seed"]))
        for col in COLUMNS:
            row.setdefault(col, "")
        rows.append(row)
        if (i + 1) % 100 == 0:
            print(f"  swept {i + 1}/{len(pop_rows)}  ({time.time() - t0:.0f}s)", flush=True)
    path = results_path("dzero/verdicts.csv")
    with open(path, "w", newline="") as fh:
        wr = csv.DictWriter(fh, fieldnames=COLUMNS, extrasaction="ignore")
        wr.writeheader()
        wr.writerows(rows)
    print(f"[20] regenerated {len(rows)} verdicts -> {rel(path)} ({time.time()-t0:.0f}s)")
    return run([])          # verify what we just wrote


