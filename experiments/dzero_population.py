def _f(x):
    return float(x) if x not in ("", None, "nan") else float("nan")


def _quantiles(xs):
    xs = sorted(xs)
    if not xs:
        return {}

    def q(p):
        if len(xs) == 1:
            return xs[0]
        i = p * (len(xs) - 1)
        lo = int(math.floor(i))
        hi = min(lo + 1, len(xs) - 1)
        return xs[lo] + (xs[hi] - xs[lo]) * (i - lo)
    return dict(n=len(xs), min=xs[0], med=q(.50), max=xs[-1])


