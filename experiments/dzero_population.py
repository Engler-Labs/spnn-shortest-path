class Witness(Exception):
    def __init__(self, sub, walk, weights, delta):
        self.sub, self.walk, self.weights, self.delta = sub, walk, weights, delta


def _search_fixed_start(adj, start, r, wstar, g, h, target, best, banned, sub, state):
    """DFS over simple paths of exactly `r` real edges from `start` (target=None: free far
    end; else the path must end at target).  Raises Witness on the first delta <= 0."""
    n = len(adj)
    seen = bytearray(n)
    seen[start] = 1
    walk = [start]
    ws = []

    def rec(v, depth, wcur):
        nonlocal best
        rem = r - depth
        if rem == 0:
            if target is not None and v != target:
                return
            disc = 0.0 if target is not None else ws[-1] / 2.0
            d = wcur - wstar - disc
            if banned is not None and (walk == banned or walk[::-1] == banned):
                return
            if d < best:
                best = d
            if d <= TOL:
                raise Witness(sub, list(walk), list(ws), d)
            return
        if target is not None:
            lb = wcur + h[rem][v] - wstar
        else:
            lb = wcur + g[rem][v] - wstar
        if lb >= best:
            return
        state["nodes"] += 1
        for u, wu in adj[v]:
            if seen[u]:
                continue
            nw = wcur + wu
            if target is not None:
                if nw + h[rem - 1][u] - wstar >= best:
                    if h[rem - 1][u] == float("inf"):
                        continue
                    break
            else:
                if rem - 1 == 0:
                    if nw - wu / 2.0 - wstar >= best:
                        break
                elif nw + g[rem - 1][u] - wstar >= best:
                    if g[rem - 1][u] == float("inf"):
                        continue
                    break
            seen[u] = 1
            walk.append(u)
            ws.append(wu)
            rec(u, depth + 1, nw)
            ws.pop()
            walk.pop()
            seen[u] = 0

    rec(start, 0, 0.0)
    return best


def _search_free_start(adj, r, wstar, g, best, sub, state, forbidden=None,
                       raise_on_hit=True):
    """DFS over simple paths of exactly `r` real edges anywhere in G (aux-free sub-case);
    both end edges discounted.  `forbidden` masks vertices used by a cycle packing."""
    n = len(adj)
    seen = bytearray(forbidden) if forbidden is not None else bytearray(n)
    walk = []
    ws = []
    hold = {"walk": None, "ws": None, "d": float("inf")}

    def rec(v, depth, wcur, wfirst):
        nonlocal best
        rem = r - depth
        if rem == 0:
            d = wcur - wstar - (wfirst + ws[-1]) / 2.0
            if d < best:
                best = d
                hold["walk"], hold["ws"], hold["d"] = list(walk), list(ws), d
            if d <= TOL and raise_on_hit:
                raise Witness(sub, list(walk), list(ws), d)
            return
        lb = wcur - wfirst / 2.0 + g[rem][v] - wstar
        if lb >= best:
            return
        state["nodes"] += 1
        for u, wu in adj[v]:
            if seen[u]:
                continue
            nw = wcur + wu
            nf = wu if depth == 0 else wfirst
            if rem - 1 == 0:
                if nw - nf / 2.0 - wu / 2.0 - wstar >= best:
                    if depth == 0:
                        continue
                    break
            else:
                nlb = nw - nf / 2.0 + g[rem - 1][u] - wstar
                if nlb >= best:
                    if g[rem - 1][u] == float("inf") or depth == 0:
                        continue
                    break
            seen[u] = 1
            walk.append(u)
            ws.append(wu)
            rec(u, depth + 1, nw, nf)
            ws.pop()
            walk.pop()
            seen[u] = 0

    for s0 in range(n):
        if seen[s0]:
            continue
        seen[s0] = 1
        walk.append(s0)
        rec(s0, 0, 0.0, 0.0)
        walk.pop()
        seen[s0] = 0
    return (best, hold) if not raise_on_hit else best


def pure_path_leg(n, adj, s, t, L, wstar, opt_path):
    """delta_min over the pure-path d = 0 members, EXACT (or raises Witness).  Each sub-case
    searched with its OWN incumbent (+inf), never the running global one."""
    m = L + 2
    state = {"nodes": 0}
    g = walk_lb_free_end(n, adj, m)
    h_t = walk_lb_to_target(n, adj, t, L)
    INF = float("inf")
    per = {}
    per["both_aux"] = _search_fixed_start(adj, s, L, wstar, g, h_t, t, INF,
                                          list(opt_path), "both_aux", state)
    per["one_aux_S"] = _search_fixed_start(adj, s, L + 1, wstar, g, None, None, INF,
                                           None, "one_aux_S", state)
    per["one_aux_T"] = _search_fixed_start(adj, t, L + 1, wstar, g, None, None, INF,
                                           None, "one_aux_T", state)
    per["aux_free"] = _search_free_start(adj, m, wstar, g, INF, "aux_free", state)
    return min(per.values()), per, state["nodes"]


